"""Builds docs/results.md + docs/figures/*.png from models/evaluation*.json and injects tables into README.md.
Every number comes from the evaluation JSON files - nothing is typed by hand."""
import json, re
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from src.config import MODEL_DIR, ROOT

SHORT = {"Historical reference (prior hypotension rate)": "Prior-rate reference", "Standard model: logistic regression": "Standard: logistic regression",
         "Standard model: random forest": "Standard: random forest", "Twin ablation: population parameters (no personalization)": "Twin, no personalization (ablation)",
         "Personalized digital twin": "Personalized digital twin", "Hybrid: standard features + twin outputs": "Hybrid: standard + twin outputs"}
COL = {"Prior-rate reference": "#9aa7b5", "Standard: logistic regression": "#16324f", "Standard: random forest": "#4b6a8a",
       "Twin, no personalization (ablation)": "#c9b8f0", "Personalized digital twin": "#0f8b8d", "Hybrid: standard + twin outputs": "#e07b39"}
plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})


def load():
    return json.load(open(MODEL_DIR / "evaluation.json")), json.load(open(MODEL_DIR / "evaluation_real.json"))


def md_table(E, split):
    r = E[split]; rows = ["| Model | ROC-AUC | Brier | Precision | Recall | F1 |", "|---|---|---|---|---|---|"]
    for m, v in r["models"].items():
        rows.append(f"| {SHORT[m]} | {v['auc']:.3f} | {v['brier']:.3f} | {v['precision']:.2f} | {v['recall']:.2f} | {v['f1']:.2f} |")
    d, h = r["auc_diff_twin_minus_lr"], r["auc_diff_hybrid_minus_lr"]
    n = list(r["models"].values())[0]
    rows.append(f"\n*{r['n_test_patients']} test patients, {n['n']:,} sessions, outcome prevalence {n['prevalence']:.1%}. AUC difference vs logistic regression (95% patient-cluster bootstrap CI): "
                f"twin {d['mean']:+.3f} ({d['lo']:+.3f} to {d['hi']:+.3f}); hybrid {h['mean']:+.3f} ({h['lo']:+.3f} to {h['hi']:+.3f}).*")
    return "\n".join(rows)


def figs(S, R):
    names = list(SHORT.values()); fig, ax = plt.subplots(1, 2, figsize=(12, 4.2), sharey=True)
    for a, E, t in ((ax[0], S, "Synthetic cohort (120 patients)"), (ax[1], R, "Real open data: HEMOBP (328 patients)")):
        vals = {SHORT[m]: v["auc"] for m, v in E["patient_holdout"]["models"].items()}
        a.barh(names[::-1], [vals[n] for n in names[::-1]], color=[COL[n] for n in names[::-1]])
        for i, n in enumerate(names[::-1]): a.text(vals[n] + .005, i, f"{vals[n]:.3f}", va="center", fontsize=9)
        a.set_xlim(0.5, 1.0); a.set_title(t, fontsize=11); a.set_xlabel("ROC-AUC (patient-grouped hold-out)")
    fig.tight_layout(); fig.savefig(ROOT / "docs/figures/auc_comparison.png", dpi=160); plt.close(fig)
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.4))
    for a, E, t in ((ax[0], S, "ROC - synthetic"), (ax[1], R, "ROC - real HEMOBP")):
        for m, v in E["patient_holdout"]["models"].items():
            if SHORT[m] in ("Prior-rate reference", "Twin, no personalization (ablation)", "Standard: random forest"): continue
            a.plot(v["roc"][0], v["roc"][1], color=COL[SHORT[m]], label=f"{SHORT[m]} ({v['auc']:.3f})", lw=2)
        a.plot([0, 1], [0, 1], ":", color="grey"); a.set_title(t); a.set_xlabel("False-positive rate"); a.set_ylabel("True-positive rate"); a.legend(fontsize=8, loc="lower right")
    fig.tight_layout(); fig.savefig(ROOT / "docs/figures/roc_curves.png", dpi=160); plt.close(fig)
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.4))
    for a, E, t in ((ax[0], S, "Calibration - synthetic"), (ax[1], R, "Calibration - real HEMOBP")):
        for m in ("Standard model: logistic regression", "Personalized digital twin", "Hybrid: standard features + twin outputs"):
            v = E["patient_holdout"]["models"][m]; a.plot(v["calib"][0], v["calib"][1], "o-", color=COL[SHORT[m]], label=SHORT[m])
        a.plot([0, 1], [0, 1], ":", color="grey"); a.set_title(t); a.set_xlabel("Mean predicted risk"); a.set_ylabel("Observed fraction"); a.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(ROOT / "docs/figures/calibration.png", dpi=160); plt.close(fig)


def main():
    S, R = load(); figs(S, R)
    block = ("### Synthetic cohort - patient-grouped hold-out\n\n" + md_table(S, "patient_holdout") + "\n\n### Real open data (HEMOBP) - patient-grouped hold-out\n\n" + md_table(R, "patient_holdout")
             + "\n\n![AUC comparison](docs/figures/auc_comparison.png)\n\n![ROC](docs/figures/roc_curves.png)")
    full = "# Results (auto-generated by `python -m src.make_report`)\n\n" + block.replace("docs/figures/", "figures/") + \
           "\n\n## Temporal hold-out\n\n### Synthetic\n\n" + md_table(S, "temporal") + "\n\n### Real HEMOBP\n\n" + md_table(R, "temporal") + "\n"
    (ROOT / "docs/results.md").write_text(full)
    rd = (ROOT / "README.md").read_text()
    rd = re.sub(r"<!--RESULTS_START-->.*<!--RESULTS_END-->", lambda m: "<!--RESULTS_START-->\n" + block + "\n<!--RESULTS_END-->", rd, flags=re.S)
    (ROOT / "README.md").write_text(rd)
    print("report written")


if __name__ == "__main__":
    main()
